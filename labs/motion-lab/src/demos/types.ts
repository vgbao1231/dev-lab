import type { ComponentType } from 'react';

export type DemoGroup = 'core' | 'gestures' | 'layout' | 'scroll' | 'accessibility';

/**
 * Everything the index page needs to know about a demo. It lives next to the
 * demo in `meta.ts` and is imported eagerly, so it must stay small: no React
 * imports, no component imports, no data beyond the spec below.
 */
export type DemoMeta = {
  /** Must match the folder name in `src/demos/`. */
  id: string;
  title: string;
  group: DemoGroup;
  /** Sort key inside the index. Gaps of 10 leave room for insertions. */
  order: number;
  summary: string;
  /** The APIs this demo is about, shown as a short reference. */
  api: string[];
  /** Mistakes that are easy to make with this API. */
  pitfalls: string[];
  /** Short snippet shown under the demo; the demo folder owns its copy. */
  code: string;
};

export type DemoModule = { default: ComponentType };

export type Demo = DemoMeta & {
  /**
   * Dynamic import generated by the registry from the demo's `index.tsx`.
   * Never replace this with a static import: it would pull every demo into the
   * entry bundle.
   */
  load: () => Promise<DemoModule>;
};
